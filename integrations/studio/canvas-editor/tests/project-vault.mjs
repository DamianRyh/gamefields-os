import assert from 'node:assert/strict';
import {parseVaultProject,createSnapshot,parseSnapshots,addSnapshot,removeSnapshot,restoreSnapshot,DRAFT_KEY} from '../lib/project-vault.ts';
import {arenaGeometry} from '../lib/arena-geometry-data.mjs';

const png='data:image/png;base64,aGVsbG8=';
const project={id:'GF-vault-test',name:'Wariant testowy',arenaModel:'octagon',length:4.962,width:4.962,sport:'Piłka nożna 1×1',surface:'EPDM',base:'#123456',zone:'#234567',outside:'#345678',lineColor:'#ffffff',lines:false,pattern:'Organic Flow',graphicOpacity:100,graphicScale:100,graphicRotation:0,scene:'day',objects:[{id:'kept-object-id',kind:'image',name:'Logo na nawierzchni',x:1,y:2,scale:100,rotation:0,opacity:100,color:'#ffffff',src:png,target:'court'}],arenaDesign:{panelColor:'#123456',frameColor:'#234567',goalColor:'#345678',finish:'matte',text:'',src:png,side:'both'}};
const clone=value=>JSON.parse(JSON.stringify(value));
const timestamp='2026-10-21T12:00:00.000Z';
const snapshot=createSnapshot(project,'  Pierwszy wariant  ','variant-1',timestamp);
assert.equal(DRAFT_KEY,'gamefields-studio-draft-v1','Existing browser drafts retain their key');
assert.equal(snapshot.name,'Pierwszy wariant');
assert.equal(snapshot.modelRevision,arenaGeometry.octagon.sourceRevision);
assert.equal(snapshot.project.objects[0].id,'kept-object-id');
assert.equal(snapshot.project.objects[0].src,png);
assert.equal(snapshot.project.arenaDesign.src,png,'Panel artwork remains available for recovery');
assert.equal(snapshot.project.type,'Nowe boisko','Legacy direct JSON obtains schema defaults');
assert.deepEqual(parseVaultProject(JSON.stringify(project)),parseVaultProject(project));
const legacyNamed={...project,name:'Octagon — projekt'};
const migrated=createSnapshot(legacyNamed,'Nazwa zapisu','legacy',timestamp);
assert.equal(migrated.project.name,'Panna Octa — projekt');
assert.equal(migrated.modelRevision,arenaGeometry.octagon.sourceRevision);
assert.equal(restoreSnapshot(migrated).name,'Panna Octa — projekt');
assert.equal(legacyNamed.name,'Octagon — projekt','Canonical name migration leaves original imported bytes/data unchanged');
assert.equal(addSnapshot(undefined,migrated).items[0].project.name,'Panna Octa — projekt');
assert.throws(()=>parseVaultProject('{broken'));
assert.throws(()=>parseVaultProject({...project,objects:[project.objects[0],project.objects[0]]}),/identyfikatory/);
assert.throws(()=>parseVaultProject({...project,length:-1}));
assert.throws(()=>createSnapshot(project,' ','empty',timestamp));
assert.throws(()=>createSnapshot(project,'x'.repeat(81),'long',timestamp));

const sourceBefore=JSON.stringify(project);
const restored=restoreSnapshot(snapshot);
restored.objects[0].name='Changed independently';
restored.arenaDesign.panelColor='#000000';
assert.equal(JSON.stringify(project),sourceBefore,'Snapshot/restore must not mutate the active project');
assert.equal(snapshot.project.objects[0].name,project.objects[0].name);
assert.equal(snapshot.project.arenaDesign.panelColor,project.arenaDesign.panelColor);
assert.notStrictEqual(snapshot.project,project);
assert.notStrictEqual(restored.objects,snapshot.project.objects);

assert.deepEqual(parseSnapshots(undefined),{schemaVersion:1,items:[]});
for(const invalid of [null,{},[],{schemaVersion:2,items:[]},{schemaVersion:1,items:null}])assert.throws(()=>parseSnapshots(invalid));
for(const patch of [{id:''},{createdAt:'not-a-date'},{name:''},{modelRevision:'bad-revision'}])assert.throws(()=>parseSnapshots({schemaVersion:1,items:[{...snapshot,...patch}]}));
assert.throws(()=>parseSnapshots({schemaVersion:1,items:[snapshot,snapshot]}),'Duplicate variant IDs rejected');
assert.throws(()=>restoreSnapshot({...snapshot,modelRevision:'0'.repeat(64)}),/rewizji/);
assert.throws(()=>restoreSnapshot({...snapshot,modelRevision:null}),/rewizji/,'Known model without its revision cannot silently restore');
const custom=clone(project);delete custom.arenaModel;
const customSnapshot=createSnapshot(custom,'Własny projekt','custom',timestamp);
assert.equal(customSnapshot.modelRevision,null);
assert.deepEqual(restoreSnapshot(customSnapshot),parseVaultProject(custom));

let library=parseSnapshots(undefined);
for(let i=0;i<6;i++)library=addSnapshot(library,createSnapshot(project,`Wariant ${i}`,`variant-${i}`,timestamp));
assert.equal(library.items.length,6);
const libraryBefore=JSON.stringify(library);
assert.throws(()=>addSnapshot(library,createSnapshot(project,'Siódmy','variant-7',timestamp)),/6 wariantów/);
assert.equal(JSON.stringify(library),libraryBefore,'Full-library failure preserves all existing records');
assert.throws(()=>parseSnapshots({schemaVersion:1,items:[...library.items,createSnapshot(project,'Siódmy','variant-7',timestamp)]}));
const removed=removeSnapshot(library,'variant-2');
assert.equal(removed.items.length,5);
assert.equal(JSON.stringify(library),libraryBefore,'Removing a variant must not mutate its source');
assert.deepEqual(removeSnapshot(library,'missing'),library);
assert.throws(()=>addSnapshot({schemaVersion:1,items:[snapshot]},snapshot),'Adding duplicate IDs must fail');
const parsed=parseSnapshots(library);
parsed.items[0].project.objects[0].name='Changed parsed copy';
assert.equal(JSON.stringify(library),libraryBefore,'Parsing creates independently recoverable project records');
console.log('PASS: legacy JSON, artwork/IDs, immutable variants, bounded six-item vault, validation and model revision recovery guards.');
